def _gcode_fixture(layers: int = 4) -> str:
    """A minimal G-code text with one extruding move per rising Z, so the indexer finds layers."""
    lines = ["; HEADER_BLOCK_START", "; generated by test", "; HEADER_BLOCK_END", "G28", "G90"]
    for i in range(1, layers + 1):
        z = round(0.2 * i, 2)
        lines.append(f"G1 Z{z} F600")
        lines.append(f"G1 X{10 + i} Y{10 + i} E{i}.0 F1200")
    return "\n".join(lines) + "\n"


class _FakeAgentClient:
    """Yields a scripted event stream for the turn loop, standing in for the real SDK client."""

    def __init__(self, events: list) -> None:
        self._events = events

    async def run_turn(self, session_id: str, user_content: list):
        for event in self._events:
            yield event


class StartupCredentialTest(unittest.TestCase):
    """Startup requires the OAuth token and reads model/effort from the environment."""

    def test_missing_token_crashes(self) -> None:
        """An absent or blank OAuth token raises StartupError so the process never serves."""
        with self.assertRaises(composition.StartupError):
            composition.require_oauth_token({})
        with self.assertRaises(composition.StartupError):
            composition.require_oauth_token({composition.OAUTH_ENV: "   "})

    def test_present_token_returned(self) -> None:
        """A present token is returned verbatim for passing on to the SDK."""
        self.assertEqual(
            composition.require_oauth_token({composition.OAUTH_ENV: "fake-token"}), "fake-token"
        )

    def test_model_effort_defaults_and_overrides(self) -> None:
        """Model/effort default to Opus at medium effort and honour the PD_* overrides."""
        self.assertEqual(
            composition.resolve_model_effort({}),
            (composition.DEFAULT_MODEL, composition.DEFAULT_EFFORT),
        )
        self.assertEqual(
            composition.resolve_model_effort({"PD_MODEL": "m", "PD_EFFORT": "high"}), ("m", "high")
        )


