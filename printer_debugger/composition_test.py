class UploadIndexTest(_StoreFixture):
    """Uploading G-code builds and stores an index that the gcode tools can answer over."""

    def test_gcode_upload_builds_and_stores_index(self) -> None:
        """A G-code upload records a file_index row, and load_gcode_tools answers over it."""
        context = AppContext(
            store=self.store,
            auth=AuthConfig(mode=AuthMode.LOCAL),
            artifacts=self.artifacts,
            on_upload=lambda artifact, body: composition.build_index_for_upload(
                self.store, self.artifacts, artifact, body
            ),
        )
        client = TestClient(create_app(context))
        session = self.store.create_session(name="s")
        response = client.post(
            f"/sessions/{session.id}/files",
            content=_gcode_fixture().encode("utf-8"),
            headers={"X-Filename": "part.gcode", "Content-Type": "text/plain"},
        )
        self.assertEqual(response.json()["kind"], "gcode")
        artifact_id = response.json()["artifact_id"]
        file_index = self.store.get_file_index(artifact_id)
        self.assertIsNotNone(file_index)
        self.assertEqual(file_index.kind.value, "gcode")

        tools = composition.load_gcode_tools(self.store, self.artifacts, session.id)
        self.assertIsNotNone(tools)
        self.assertGreater(tools.get_layer_table()["count"], 0)

    def test_non_gcode_upload_builds_no_index(self) -> None:
        """A .3mf upload stores the blob but builds no index (mesh read on demand)."""
        stored: list = []
        context = AppContext(
            store=self.store,
            auth=AuthConfig(mode=AuthMode.LOCAL),
            artifacts=self.artifacts,
            on_upload=lambda artifact, body: composition.build_index_for_upload(
                self.store, self.artifacts, artifact, body
            ),
        )
        client = TestClient(create_app(context))
        session = self.store.create_session(name="s")
