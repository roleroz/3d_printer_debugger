class ApproveBridgeTest(_StoreFixture):
    """The approve bridge publishes a proposal, routes the vote through resolve, and records it."""

    def test_approve_routes_to_gate_resolve_and_records(self) -> None:
        """A published proposal, resolved as approved, returns True and records an approved row."""
        from printer_debugger.web.sse import SseHub

        hub = SseHub()
        gate = composition.make_gate(self.store, hub)
        session = self.store.create_session(name="s")
        approve = composition.make_approve(self.store, gate, session.id)

        async def scenario() -> bool:
            task = asyncio.create_task(approve("G28", ()))
            await asyncio.sleep(0)  # let the proposal publish and the gate reach its await.
            proposal = hub.missed_since(session.id, 0)[0]
            tool_call_id = proposal.data["tool_call_id"]
            self.assertTrue(gate.resolve(tool_call_id, True, "tester"))
            approved = await task
            self._tool_call_id = tool_call_id
            return approved

        self.assertTrue(asyncio.run(scenario()))
        approval = self.store.get_approval(self._tool_call_id)
        self.assertEqual(approval.decision, ApprovalDecision.APPROVED)
        self.assertEqual(approval.decided_by, "tester")

    def test_reject_records_rejection(self) -> None:
        """A proposal resolved as rejected returns False and records a rejected row."""
        from printer_debugger.web.sse import SseHub

        hub = SseHub()
        gate = composition.make_gate(self.store, hub)
        session = self.store.create_session(name="s")
        approve = composition.make_approve(self.store, gate, session.id)

        async def scenario() -> bool:
            task = asyncio.create_task(approve("G28", ()))
            await asyncio.sleep(0)
            tool_call_id = hub.missed_since(session.id, 0)[0].data["tool_call_id"]
            gate.resolve(tool_call_id, False, "tester")
            self._tool_call_id = tool_call_id
            return await task

        self.assertFalse(asyncio.run(scenario()))
        self.assertEqual(
            self.store.get_approval(self._tool_call_id).decision, ApprovalDecision.REJECTED
        )


class SubmissionLocusTest(_StoreFixture):
    """A gated command is submitted exactly once: the gate decides, the tool submits."""

    def test_gate_does_not_submit_and_tool_submits_once(self) -> None:
        """Approving at the gate submits nothing; propose_command then submits exactly one POST."""
        from printer_debugger.printer.moonraker import MoonrakerClient
        from printer_debugger.printer.tools import PrinterTools
        from printer_debugger.web.sse import SseHub

        posts: list[tuple[str, str]] = []

        def transport(method: str, url: str, body: bytes | None):
            posts.append((method, url))
            return 200, b"{}"

        hub = SseHub()
        gate = composition.make_gate(self.store, hub)
        session = self.store.create_session(name="s")
        approve = composition.make_approve(self.store, gate, session.id)

        async def gate_scenario() -> bool:
            task = asyncio.create_task(approve("G28", ()))
            await asyncio.sleep(0)
            tool_call_id = hub.missed_since(session.id, 0)[0].data["tool_call_id"]
            gate.resolve(tool_call_id, True, "tester")
            return await task

        self.assertTrue(asyncio.run(gate_scenario()))
        self.assertEqual(posts, [], "the gate decides only; it must not submit to the printer")

        submit = composition.make_command_submitter("http://printer:7125", transport)
        tools = PrinterTools(
            MoonrakerClient(base_url="http://printer:7125", transport=transport), gate=submit
        )
        result = tools.propose_command("G28")
        self.assertTrue(result["executed"])
        submit_posts = [p for p in posts if p[0] == "POST" and "gcode/script" in p[1]]
        self.assertEqual(len(submit_posts), 1, "the command reaches the printer exactly once")

    def test_submitter_reports_unreachable(self) -> None:
        """The submitter reports an unreachable printer instead of raising into the tool."""
        from printer_debugger.printer.moonraker import PrinterUnreachable

        def transport(method: str, url: str, body: bytes | None):
            raise PrinterUnreachable("no route")

        submit = composition.make_command_submitter("http://printer:7125", transport)
        outcome = submit("G28", Classification(flags=(), refused=False))
        self.assertFalse(outcome["executed"])
        self.assertIn("unreachable", outcome["reason"])


